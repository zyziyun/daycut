"""Generate the Reference pages of the docs from the engine's own sources, so they never drift.

    python3 apps/docs/scripts/gen_reference.py          (or: npm run gen -w apps/docs)

Writes (English; other locales fall back to these):
  src/content/docs/reference/workflows/<name>.md   <- workflows/<name>/WORKFLOW.md
  src/content/docs/reference/engine/<slug>.md      <- references/<NAME>.md (long-form engine notes)
  src/content/docs/reference/effects.md            <- references/EFFECTS.md (itself generated from lib/vstudio/effects.py)
  src/content/docs/reference/captions.md           <- references/CAPTION_RULES.md
  src/content/docs/reference/messages.md           <- references/MESSAGES.md (itself generated from messages.py)
  src/content/docs/reference/platforms.md          <- lib/vstudio/platform.py (live profiles) + references/PLATFORMS.md
  src/content/docs/reference/persona.md            <- persona.example.yaml
  src/content/docs/reference/cli.md                <- `python -m vstudio.<module> --help`

Every generated file starts with a "generated" comment; edit the source, then re-run this script.
"""
