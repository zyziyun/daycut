def gen_persona() -> None:
    src = REPO / "persona.example.yaml"
    text = src.read_text(encoding="utf-8")
    # Top-level sections and the comment right after the key (if any).
    sections, cur = [], None
    for line in text.splitlines():
        m = re.match(r"^([a-z_]+):(.*)$", line)
        if m:
            cur = [m.group(1), m.group(2).partition("#")[2].strip(), []]
            sections.append(cur)
        elif cur and re.match(r"^  [a-z_]+:", line):
            key = line.split(":")[0].strip()
            if key not in cur[2]:
                cur[2].append(key)
    rows = ["| Section | What it sets | Keys |", "|---|---|---|"]
    for name, comment, keys in sections:
        ks = ", ".join(f"`{k}`" for k in keys[:12]) + (" …" if len(keys) > 12 else "")
        what = PERSONA_SECTIONS.get(name) or comment.replace('|', '/') or '—'
        rows.append(f"| [`{name}`](#{name}) | {what} | {ks} |")
    blocks = []
    lines = text.splitlines()
    idx = [i for i, l in enumerate(lines) if re.match(r"^[a-z_]+:", l)] + [len(lines)]
    for a, b in zip(idx, idx[1:]):
        name = lines[a].split(":")[0]
        # Include comment lines that sit just above a section with it.
        chunk = "\n".join(lines[a:b]).rstrip()
        while chunk.endswith("\n") or (chunk.splitlines() and chunk.splitlines()[-1].startswith("#")):
            chunk = "\n".join(chunk.splitlines()[:-1]).rstrip()
        blocks.append(f"### `{name}`\n\n```yaml\n{chunk}\n```\n")
    header = " ".join(l[1:].strip() for l in lines[: idx[0]] if l.startswith("#"))
    body = (front("persona.yaml options", "Every option in persona.local.yaml: speeds, loudness, brand colours and "
                  "theme, platform overrides, tags, voice rules, term fixes, fonts and AI routing.")
            + STAMP.format(src="persona.example.yaml") + "\n\n" + source_note("persona.example.yaml")
            + "Everything that is taste rather than technique lives in one file. Copy the example and edit it:\n\n"
            "```bash\ncp persona.example.yaml persona.local.yaml   # in the skill folder; git-ignored\n```\n\n"
            "The Mac app keeps the same settings under **Settings**; the skill reads `persona.local.yaml`. "
            "Any key you leave out keeps the default shown here.\n\n"
            + (f"> {header}\n\n" if header else "")
            + "## Sections\n\n" + "\n".join(rows) + "\n\n## Full example, section by section\n\n" + "\n".join(blocks))
    write(OUT / "persona.md", body)


