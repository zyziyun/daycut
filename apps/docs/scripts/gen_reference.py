# Repo file -> docs route (for rewriting links between generated pages).
ROUTES = {f"references/{k}": f"/docs/reference/engine/{v[0]}/" for k, v in ENGINE.items()}
ROUTES.update({f"references/{k}": f"/docs/reference/{v}/" for k, v in TOP.items()})
ROUTES.update({f"workflows/{k}/WORKFLOW.md": f"/docs/reference/workflows/{k}/" for k in WORKFLOWS})
ROUTES["persona.example.yaml"] = "/docs/reference/persona/"

STAMP = "<!-- Generated by apps/docs/scripts/gen_reference.py from {src}. Do not edit here: edit the source and re-run. -->"


def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def front(title: str, description: str, order: int | None = None, extra: str = "") -> str:
    fm = ["---", f"title: {yaml_str(title)}", f"description: {yaml_str(description)}"]
    if order is not None:
        fm.append(f"sidebar:\n  order: {order}")
    fm.append("editUrl: false")
    if extra:
        fm.append(extra)
    fm.append("---")
    return "\n".join(fm) + "\n"


def split_title(md: str) -> tuple[str, str]:
    lines = md.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("# "):
            return line[2:].strip(), "\n".join(lines[:i] + lines[i + 1:]).lstrip("\n")
    return "", md


def first_paragraph(md: str, limit: int = 158) -> str:
    in_code = False
    for block in re.split(r"\n\s*\n", md):
        b = block.strip()
        if b.startswith("```"):
            in_code = not in_code if b.count("```") % 2 else in_code
            continue
        if in_code or not b or b[0] in "#|>-<*!" or b.startswith("    "):
            continue
        text = re.sub(r"\s+", " ", b)
        text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
        text = text.replace("**", "").replace("`", "")
        if len(text) > limit:
            text = text[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"
        return text
    return ""


def rewrite_links(md: str, src: Path) -> str:
    base = src.parent

    def fix(m: re.Match) -> str:
        text, target = m.group(1), m.group(2)
        if re.match(r"^[a-z]+:|^#|^/", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        resolved = os.path.normpath(os.path.join(base.relative_to(REPO), path)).replace(os.sep, "/")
        if resolved in ROUTES:
            url = ROUTES[resolved] + (f"#{anchor.lower()}" if anchor else "")
        else:
            url = GH + resolved + (f"#{anchor}" if anchor else "")
        return f"[{text}]({url})"

    out, in_code = [], False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        out.append(line if in_code else re.sub(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)\)", fix, line))
    md = "\n".join(out)
    # Images: point at GitHub raw so they render without copying assets.
    md = re.sub(r"!\[([^\]]*)\]\((?!https?:)([^)]+)\)",
                lambda m: f"![{m.group(1)}](https://raw.githubusercontent.com/zyziyun/reelfold/main/"
                f"{os.path.normpath(os.path.join(src.parent.relative_to(REPO), m.group(2)))})", md)
    return md


def demote(md: str) -> str:
    """Generated bodies keep their own heading levels (## and below); a stray `# ` becomes `##`."""
    out, in_code = [], False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        out.append("#" + line if (not in_code and line.startswith("# ")) else line)
    return "\n".join(out)


def source_note(rel: str) -> str:
    return (f":::note[Source]\nThis page is generated from [`{rel}`]({GH}{rel}) in the repository, "
            "the same file the engine and the Claude Code skill read.\n:::\n\n")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")
    print("wrote", path.relative_to(DOCS))


def gen_workflows() -> None:
    for name, (order, desc) in WORKFLOWS.items():
        src = REPO / "workflows" / name / "WORKFLOW.md"
        rel = src.relative_to(REPO).as_posix()
        h1, body = split_title(src.read_text(encoding="utf-8"))
        subtitle = re.split(r"\s+[—:-]\s+", h1, maxsplit=1)
        title = f"{name}" + (f": {subtitle[1]}" if len(subtitle) > 1 else "")
        body = demote(rewrite_links(body, src))
        fm = (f"---\ntitle: {yaml_str(title)}\ndescription: {yaml_str(desc)}\n"
              f"sidebar:\n  label: {yaml_str(name)}\n  order: {order}\neditUrl: false\n---\n")
        write(OUT / "workflows" / f"{name}.md", fm
              + STAMP.format(src=rel) + "\n\n" + source_note(rel) + body)


def gen_engine() -> None:
    for fname, (slug, order) in ENGINE.items():
        src = REPO / "references" / fname
        rel = src.relative_to(REPO).as_posix()
        h1, body = split_title(src.read_text(encoding="utf-8"))
        desc = first_paragraph(body) or h1
        write(OUT / "engine" / f"{slug}.md",
              front(h1, desc, order) + STAMP.format(src=rel) + "\n\n" + source_note(rel) + demote(rewrite_links(body, src)))


def gen_top(fname: str, slug: str, title: str, desc: str, intro: str = "") -> None:
    src = REPO / "references" / fname
    rel = src.relative_to(REPO).as_posix()
    _, body = split_title(src.read_text(encoding="utf-8"))
    write(OUT / f"{slug}.md",
          front(title, desc) + STAMP.format(src=rel) + "\n\n" + source_note(rel) + intro + demote(rewrite_links(body, src)))


def gen_platforms() -> None:
    from vstudio import platform as P

    rows_by_group = []
    for group, names in P.GROUPS.items():
        rows = []
        for name in names:
            keys = [k for k in P.list_profiles() if k.split(":")[0] == name]
            for k in keys:
                pr = P.profile(*k.split(":"), use_persona=False)
                ln = pr.length or {}
                sweet = ln.get("sweet") or ["", ""]
                title = "none" if not pr.title_max else f"{pr.title_max:g}"
                cov = pr.cover or {}
                rows.append(
                    f"| `{k}` | {pr.label} | {pr.w}×{pr.h} ({pr.aspect}) | {cov.get('w')}×{cov.get('h')} | "
                    f"{sweet[0]}–{sweet[1]} s / max {fmt_s(ln.get('max'))} | {title} | "
                    f"{pr.loudness.get('lufs'):g} LUFS / {pr.loudness.get('tp'):g} dBTP |")
        rows_by_group.append((P.GROUP_LABELS[group]["en"], rows))

    pub = ["| Platform | Upload page (assisted) | Official API (opt-in only) |", "|---|---|---|"]
    for name in P.ORDER:
        d = P.PUBLISHING.get(name, {})
        up = d.get("upload_url")
        pub.append(f"| `{name}` | {f'<{up}>' if up else d.get('note', '—')} | {d.get('api') or '—'} |")

    src = REPO / "references" / "PLATFORMS.md"
    _, prose = split_title(src.read_text(encoding="utf-8"))
    parts = [front("Platform specs", "Every platform profile Reelfold exports to: canvas, cover, length, title limit "
                   "and loudness, generated from the engine's own profiles."),
             STAMP.format(src="lib/vstudio/platform.py + references/PLATFORMS.md"), "",
             source_note("lib/vstudio/platform.py"),
             "One clean master becomes one file per platform below. Pick targets with `--platforms` "
             "(`python -m vstudio.export master.mp4 --platforms xiaohongshu:vertical,douyin,youtube-shorts`), in a "
             "batch spec, or in the app's export step. Print the live table on your machine with "
             "`cd lib && python3 -m vstudio.platform`; override any value per creator in `persona.local.yaml` "
             "under `platforms.<name>`.\n"]
    head = "| Profile | Platform | Canvas | Cover | Length (sweet spot / max) | Title max | Loudness |\n|---|---|---|---|---|---|---|"
    for label, rows in rows_by_group:
        parts.append(f"## {label}\n\n{head}\n" + "\n".join(rows) + "\n")
    parts.append("## How each platform is published\n\nPublishing is assisted by default: the app opens the "
                 "platform's own upload page, fills in the file and the copy, and you press publish. An API uploader "
                 "is only used when you configure one and confirm each post. See [Assisted publishing]"
                 "(/docs/concepts/publishing/).\n\n" + "\n".join(pub) + "\n")
    parts.append("## Notes and sources\n\n" + demote(demote(rewrite_links(prose, src)).replace("\n## ", "\n### ")))
    write(OUT / "platforms.md", "\n".join(parts))


def fmt_s(s) -> str:
    if not s:
        return "—"
    s = int(s)
    if s >= 3600:
        return f"{s / 3600:g} h"
    if s >= 60:
        return f"{s // 60} min" + (f" {s % 60} s" if s % 60 else "")
    return f"{s} s"


