def gen_cli() -> None:
    env = dict(os.environ, PYTHONPATH=str(REPO / "lib"), COLUMNS="100", NO_COLOR="1")
    parts = [front("CLI", "Command-line reference for the Reelfold engine (python -m vstudio.*): intake, project, "
                   "batch, cleanup, export, reframe, platform, effects, llm, retouch."),
             STAMP.format(src="`python -m vstudio.<module> --help`"), "",
             "The engine is a Python package (`vstudio`, in `lib/`). The Mac app and the Claude Code skill both call "
             "these commands; you can run them yourself from a terminal:\n\n```bash\n"
             "cd ~/.claude/skills/video-studio        # or your clone of the repository\n"
             "export PYTHONPATH=\"$PWD/lib:$PYTHONPATH\"\npython3 -m vstudio.intake --help\n```\n\n"
             "Every command that reports something accepts `--json` for one machine-readable document. "
             "Each workflow also has its own scripts under `workflows/<name>/scripts`; see "
             "[Workflows](/docs/reference/workflows/talkinghead/).\n\n| Command | What it does |\n|---|---|"]
    parts += [f"| [`vstudio.{m}`](#vstudio{m}) | {d} |" for m, d in CLI]
    parts.append("")
    for mod, desc in CLI:
        args = ["--help"] if mod != "platform" else []
        try:
            res = subprocess.run([sys.executable, "-m", f"vstudio.{mod}", *args], cwd=REPO / "lib", env=env,
                                 capture_output=True, text=True, timeout=120)
            out = (res.stdout or res.stderr).rstrip()
        except Exception as e:  # pragma: no cover
            out = f"(could not run: {e})"
        out = re.sub(r"^usage: retouch\.py", "usage: python -m vstudio.retouch", out)
        out = out.replace(str(REPO), "<repo>").replace(str(Path.home()), "~")
        parts.append(f"## `vstudio.{mod}`\n\n{desc}\n\n```text\n{out}\n```\n")
    write(OUT / "cli.md", "\n".join(parts))


